"""The in-app user handbook (`/help`) and the shared help widgets.

The handbook is **one set of Markdown files** in `docs/user/<language>/`; this
module only presents them (`meadow.frontend.help_content` does the parsing,
rendering, searching). There is no build step: the frontend reads the files at
startup, so the handbook cannot drift from the UI it documents.

Two surfaces use this module:

- the **`/help` page** — chapter list, chapter body, search;
- **`info_button`/`hint_label`** — the small widgets other pages use to explain a
  concept in one line and link to the chapter that explains it in full
  ("tooltip = short answer, handbook = long answer", see `docs/AGENTS.md`).

Deep links stay language-neutral: the chapter **ids are identical in every
language** (`?page=product-form`), only the rendered text differs, and a section
is addressed with `?anchor=<heading-id>` (the renderer's id, not a hand-written
slug — `tests/test_help.py` asserts they match).
"""

from __future__ import annotations

import re

from nicegui import app, ui

from meadow.frontend.help_content import (
    DOCS_ROOT,
    Hit,
    Page,
    available_languages,
    catalog,
    chapter_title,
    find_page,
    help_target,
    resolve_language,
    search,
)
from meadow.frontend.i18n import current_locale, t
from meadow.frontend.layout import PAGE_TIMEOUT, build_shell

#: Handbook images (generated by `scripts/docs_screenshots.py`) — mounted so a
#: chapter can reference them with an absolute path (`/help-assets/<file>.png`).
app.add_static_files("/help-assets", str(DOCS_ROOT / "assets"))

#: User preference (not part of the session — it survives signing out).
HELP_LANGUAGE_KEY = "help_language"

#: Anchors are renderer-generated ids; only scroll to a value of that shape.
_ANCHOR = re.compile(r"^[a-z0-9_-]+$")

#: Quasar resets the heading margins, so the rendered chapter needs its own ones.
ui.add_css(
    """
    .help-body h1 { font-size: 1.75rem; font-weight: 600; margin: 0 0 0.75rem; }
    .help-body h2 { font-size: 1.25rem; font-weight: 600; margin: 2rem 0 0.5rem;
                    padding-top: 0.75rem; border-top: 1px solid rgba(0,0,0,0.08); }
    .help-body h3 { font-size: 1.05rem; font-weight: 600; margin: 1.5rem 0 0.4rem; }
    .help-body p, .help-body li { line-height: 1.6; margin: 0.5rem 0; }
    .help-body ul, .help-body ol { padding-left: 1.25rem; }
    .help-body code { background: rgba(0,0,0,0.05); padding: 0 0.25rem; border-radius: 3px; }
    .help-body pre { background: rgba(0,0,0,0.05); padding: 0.75rem; border-radius: 6px;
                     overflow-x: auto; }
    .help-body table { border-collapse: collapse; margin: 0.75rem 0; width: 100%; }
    .help-body th, .help-body td { border: 1px solid rgba(0,0,0,0.12);
                                   padding: 0.4rem 0.6rem; text-align: left; }
    .help-body a { color: var(--q-primary); text-decoration: underline; }
    /* Chapter images are generated at 1600px width — constrain them explicitly
       instead of relying on the stylesheet's image preflight. */
    .help-body img { max-width: 100%; height: auto; margin: 0.75rem 0;
                     border: 1px solid rgba(0,0,0,0.08); border-radius: 6px; }
    """,
    shared=True,
)


def handbook_language() -> str:
    """Returns the handbook language: the user's choice, else the UI locale."""
    languages = available_languages()
    stored = app.storage.user.get(HELP_LANGUAGE_KEY)
    if stored in languages:
        return str(stored)
    return resolve_language(current_locale(), languages)


def _tooltip_text(hint_key: str, page_id: str) -> str:
    """Builds the tooltip: the one-line answer plus the chapter it links to."""
    title = chapter_title(page_id, handbook_language())
    link = t("help.open").format(chapter=title) if title else ""
    hint = t(hint_key) if hint_key else ""
    return "\n\n".join(part for part in (hint, link) if part)


def info_button(hint_key: str, page_id: str, anchor: str = "") -> ui.button:
    """Renders a `help_outline` button: one-line answer plus a link to the chapter.

    Use it for a **concept** the user has to understand (not for every field) and
    only once per screen — see the help rules in `docs/AGENTS.md`.
    """
    button = ui.button(icon="help_outline").props("flat dense shrink-0")
    button.tooltip(_tooltip_text(hint_key, page_id))
    button.on_click(lambda: ui.navigate.to(help_target(page_id, anchor)))
    return button


def chapter_button(page_id: str, anchor: str = "") -> ui.button:
    """Renders the handbook entry point of a page (no separate hint text).

    One per working area: the page itself should explain what it shows, the button
    only opens the chapter that explains how to work with it.
    """
    return info_button("help.page", page_id, anchor)


def hint_label(text_key: str) -> None:
    """Renders the one-line explanation under a field or in a dialog header."""
    ui.label(t(text_key)).classes("text-caption text-gray-500")


@ui.page("/help", response_timeout=PAGE_TIMEOUT)
async def help_page(page: str = "", q: str = "", anchor: str = "") -> None:
    """Handbook page: chapter list, chapter body and search (`?page=&q=&anchor=`)."""
    await build_shell(active="/help")
    languages = available_languages()
    with ui.column().classes("w-full p-6 gap-3"):
        if not languages:
            ui.label(t("help.title")).classes("text-h4")
            ui.label(t("help.empty")).classes("text-subtitle1 text-negative")
            return

        language = handbook_language()
        chapters = catalog().get(language, ())
        state = {"page": page, "q": q, "anchor": anchor}

        with ui.row().classes("w-full items-center gap-2"):
            ui.label(t("help.title")).classes("text-h4 grow")
            if len(languages) > 1:
                ui.select(
                    {code: code.upper() for code in languages},
                    value=language,
                    label=t("help.language"),
                    on_change=_set_handbook_language,
                ).props("outline dense").classes("w-40")
        ui.label(t("help.subtitle")).classes("text-subtitle1")

        search_input = ui.input(
            label=t("help.search"), placeholder=t("help.search_hint"), value=q
        ).props("outline dense clearable debounce=300")
        search_input.classes("w-full max-w-2xl")

        @ui.refreshable
        def render_body() -> None:
            query = str(state["q"] or "").strip()
            if query:
                _render_results(chapters, query)
                return
            current = find_page(chapters, str(state["page"] or "")) or (
                chapters[0] if chapters else None
            )
            if current is None:
                ui.label(t("help.empty")).classes("text-negative")
                return
            _render_chapter(chapters, current, str(state["anchor"] or ""))

        async def _on_search(event) -> None:
            state["q"] = event.value or ""
            # A new search leaves the chapter context, so the anchor is dropped.
            state["anchor"] = ""
            render_body.refresh()
            # The results replace a possibly long chapter above the current scroll
            # position — without this the hits stay off screen.
            await ui.run_javascript("window.scrollTo({top: 0})", timeout=2)

        search_input.on_value_change(_on_search)
        render_body()


def _set_handbook_language(event) -> None:
    """Stores the handbook language preference and reloads the page."""
    app.storage.user[HELP_LANGUAGE_KEY] = event.value
    ui.navigate.reload()


def _render_results(chapters: tuple[Page, ...], query: str) -> None:
    """Renders the hit list of a search."""
    hits = search(chapters, query)
    ui.label(t("help.results").format(count=len(hits), query=query)).classes(
        "text-subtitle2 text-gray-600"
    )
    if not hits:
        ui.label(t("help.no_results")).classes("text-caption")
        return
    with ui.column().classes("w-full max-w-3xl gap-1"):
        for hit in hits:
            _render_hit(hit)


def _render_hit(hit: Hit) -> None:
    """Renders one search result as a clickable row."""
    with (
        ui.column()
        .classes("w-full gap-0 p-2 rounded cursor-pointer hover:bg-gray-100")
        .on("click", lambda h=hit: ui.navigate.to(help_target(h.page_id, h.anchor)))
    ):
        ui.label(hit.label).classes("text-subtitle2")
        ui.label(hit.snippet).classes("text-caption text-gray-600")


def _render_chapter(chapters: tuple[Page, ...], chapter: Page, anchor: str) -> None:
    """Renders the chapter list on the left and the chapter body on the right."""
    with ui.row().classes("w-full items-start gap-6 no-wrap"):
        with (
            ui.column()
            .classes("w-56 shrink-0 gap-0")
            .style("position: sticky; top: 1rem; align-self: flex-start")
        ):
            ui.label(t("help.chapters")).classes("text-caption text-gray-500 mb-1")
            for entry in chapters:
                selected = entry.id == chapter.id
                classes = "w-full px-2 py-1 rounded cursor-pointer text-body2"
                classes += " bg-primary text-white" if selected else " hover:bg-gray-100"
                with (
                    ui.row()
                    .classes(classes)
                    .on("click", lambda e=entry: ui.navigate.to(help_target(e.id)))
                ):
                    ui.label(entry.title)
        with ui.column().classes("grow max-w-3xl"):
            ui.html(f'<div class="help-body">{chapter.html}</div>')
    _scroll_to(anchor, chapter)


def _scroll_to(anchor: str, chapter: Page) -> None:
    """Scrolls to a section after the browser has the rendered DOM.

    The page is built client-side, so the browser cannot jump to `#anchor` on its
    own; the delay lets NiceGUI finish the render before we ask it to scroll.
    """
    if not anchor or not _ANCHOR.match(anchor):
        return
    if not any(section.anchor == anchor for section in chapter.sections):
        return

    async def scroll() -> None:
        await ui.run_javascript(
            f"document.getElementById('{anchor}')?.scrollIntoView({{block: 'start'}})",
            timeout=2,
        )

    ui.timer(0.3, scroll, once=True)
